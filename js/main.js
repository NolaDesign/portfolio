const VIEW_ROUTES = {

  'view-home':
    '#home',

  'view-projects':
    '#projects',

  'view-about':
    '#about',

  'view-contact':
    '#contact'

};


const HASH_ROUTES = {

  '#home':
    'view-home',

  '#projects':
    'view-projects',

  '#about':
    'view-about',

  '#contact':
    'view-contact'

};


/* =========================================================
   VIEW TONEN
   ========================================================= */

function showView(viewId) {

  const target =
    document.getElementById(
      viewId
    );


  if (!target) {

    return;

  }


  document
    .querySelectorAll(
      '.view-section'
    )
    .forEach(view => {

      view.classList.remove(
        'active'
      );

    });


  target.classList.add(
    'active'
  );


  /* Actieve knop in menu */

  document
    .querySelectorAll(
      '.nav-btn'
    )
    .forEach(button => {

      button.classList.toggle(

        'active',

        button.dataset.target ===
          viewId

      );

    });


  /* Mobiele menu sluiten */

  const navLinks =
    document.querySelector(
      '.nav-links'
    );


  if (navLinks) {

    navLinks.classList.remove(
      'open'
    );

  }


  /* Naar boven scrollen */

  window.scrollTo(
    0,
    0
  );

}


/* =========================================================
   NAAR EEN PAGINA
   ========================================================= */

function navigateToView(viewId) {

  const hash =
    VIEW_ROUTES[
      viewId
    ];


  if (!hash) {

    return;

  }


  /*
   * Geen pushState meer.
   *
   * We veranderen alleen de hash.
   * De browser maakt daarmee zelf
   * de geschiedenis aan.
   */

  if (
    window.location.hash === hash
  ) {

    showView(
      viewId
    );

  }

  else {

    window.location.hash =
      hash;

  }

}


