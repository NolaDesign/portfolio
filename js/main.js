/* =========================================================
   LIGHTBOX
   ========================================================= */

function openLightbox(
  media
) {

  if (
    !media ||
    media.type !== 'img'
  ) {

    return;

  }


  const modal =
    document.getElementById(
      'lightbox-modal'
    );


  const image =
    document.getElementById(
      'lightbox-img'
    );


  if (
    !modal ||
    !image
  ) {

    return;

  }


  image.src =
    media.path;


  image.alt =
    media.caption ||
    'Vergrote afbeelding';


  modal.classList.add(
    'open'
  );

}


/* =========================================================
   LIGHTBOX SLUITEN
   ========================================================= */

function closeLightbox() {

  const modal =
    document.getElementById(
      'lightbox-modal'
    );


  if (modal) {

    modal.classList.remove(
      'open'
    );

  }

}


